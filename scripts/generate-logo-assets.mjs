/**
 * Regenerates brand assets from the source PNG wordmark:
 *   SOLOKNUCKLE_logo.png  ->  assets/soloknuckle-logo.svg + assets/logo.ascii.txt
 *
 * Uses only the Node standard library. The wordmark is traced into a minimal
 * set of axis-aligned rectangles (horizontal runs merged vertically), so the
 * SVG reproduces the original design — chunky blocks *and* the thin circuit
 * traces — as crisp, resolution-independent vectors.
 *
 * Usage: node scripts/generate-logo-assets.mjs
 */
import fs from 'fs';
import path from 'path';
import zlib from 'zlib';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(root, 'SOLOKNUCKLE_logo.png');
const OUT_DIR = path.join(root, 'assets');

// ---------- PNG decode (8-bit RGB, non-interlaced) ----------
const png = fs.readFileSync(SRC);
let off = 8;
let width = 0, height = 0, bitDepth = 0, colorType = 0;
const idat = [];
while (off < png.length) {
  const len = png.readUInt32BE(off);
  const type = png.toString('ascii', off + 4, off + 8);
  const data = png.subarray(off + 8, off + 8 + len);
  if (type === 'IHDR') {
    width = data.readUInt32BE(0);
    height = data.readUInt32BE(4);
    bitDepth = data[8];
    colorType = data[9];
  } else if (type === 'IDAT') {
    idat.push(data);
  }
  off += 12 + len;
  if (type === 'IEND') break;
}
if (bitDepth !== 8 || colorType !== 2) {
  throw new Error(`Expected 8-bit RGB PNG, got depth=${bitDepth} colorType=${colorType}`);
}
const raw = zlib.inflateSync(Buffer.concat(idat));
const stride = width * 3;
const bpp = 3;
const img = Buffer.alloc(height * stride);
const paeth = (a, b, c) => {
  const p = a + b - c;
  const pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
  return pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
};
let pos = 0;
for (let y = 0; y < height; y++) {
  const f = raw[pos++];
  const lineStart = pos;
  pos += stride;
  const out = img.subarray(y * stride, (y + 1) * stride);
  for (let x = 0; x < stride; x++) {
    const left = x >= bpp ? out[x - bpp] : 0;
    const up = y > 0 ? img[(y - 1) * stride + x] : 0;
    const ul = y > 0 && x >= bpp ? img[(y - 1) * stride + x - bpp] : 0;
    let v = raw[lineStart + x];
    switch (f) {
      case 1: v += left; break;
      case 2: v += up; break;
      case 3: v += (left + up) >> 1; break;
      case 4: v += paeth(left, up, ul); break;
      default: break;
    }
    out[x] = v & 0xff;
  }
}
const lum = (x, y) => {
  const i = y * stride + x * 3;
  return (img[i] + img[i + 1] + img[i + 2]) / 3;
};

// ---------- Binary bitmap + horizontal runs per row ----------
const THRESHOLD = 127;
const solid = (x, y) => lum(x, y) > THRESHOLD;
const runsPerRow = [];
for (let y = 0; y < height; y++) {
  const runs = [];
  let x = 0;
  while (x < width) {
    if (solid(x, y)) {
      const start = x;
      while (x < width && solid(x, y)) x++;
      runs.push([start, x]);
    } else x++;
  }
  runsPerRow.push(runs);
}

// ---------- Merge runs vertically into rectangles ----------
const TOL = 3;      // edge tolerance when merging across rows
const MIN_SIDE = 3; // drop specks smaller than this on either axis
const rects = [];
let open = [];
const closeAll = (active) => {
  for (const r of active) {
    const w = r.x1 - r.x0, h = r.y1 - r.y0;
    if (w >= MIN_SIDE && h >= MIN_SIDE) rects.push({ x: r.x0, y: r.y0, w, h });
  }
};
for (let y = 0; y <= height; y++) {
  const runs = y < height ? runsPerRow[y] : [];
  const nextOpen = [];
  for (const [s, e] of runs) {
    const match = open.find(o => Math.abs(o.x0 - s) <= TOL && Math.abs(o.x1 - e) <= TOL);
    if (match) {
      match.x0 = Math.min(match.x0, s);
      match.x1 = Math.max(match.x1, e);
      match.y1 = y + 1;
      if (!nextOpen.includes(match)) nextOpen.push(match);
    } else {
      nextOpen.push({ x0: s, x1: e, y0: y, y1: y + 1 });
    }
  }
  closeAll(open.filter(o => !nextOpen.includes(o)));
  open = nextOpen;
}
closeAll(open);
console.log(`traced ${rects.length} rectangles from ${width}x${height}`);

// ---------- Emit SVG (self-contained dark panel: renders correctly on both GitHub light and dark themes) ----------
fs.mkdirSync(OUT_DIR, { recursive: true });
const PAD = 24;
const rectsSvg = rects
  .map(r => `    <rect x="${r.x}" y="${r.y}" width="${r.w}" height="${r.h}"/>`)
  .join('\n');
const svg = `<!-- Generated by scripts/generate-logo-assets.mjs from SOLOKNUCKLE_logo.png — do not edit by hand -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-PAD} ${-PAD} ${width + 2 * PAD} ${height + 2 * PAD}" role="img" aria-label="SOLO KNUCKLE">
  <rect x="${-PAD}" y="${-PAD}" width="${width + 2 * PAD}" height="${height + 2 * PAD}" rx="36" fill="#0d1015"/>
  <g fill="#eef2f6">
${rectsSvg}
  </g>
</svg>
`;
const svgPath = path.join(OUT_DIR, 'soloknuckle-logo.svg');
fs.writeFileSync(svgPath, svg);
console.log(`wrote ${svgPath} (${(svg.length / 1024).toFixed(1)} kB)`);

// ---------- Emit ASCII (from traced rects, half-block pairs) ----------
// Analytic coverage: a cell is "on" when the traced rectangles cover enough
// of it. This uses the clean vector geometry instead of noisy pixels, so
// counters (holes) in O/U/C/K stay open and letters read clearly.
const COLS = 90;
const box = rects.reduce(
  (a, r) => ({
    x0: Math.min(a.x0, r.x), y0: Math.min(a.y0, r.y),
    x1: Math.max(a.x1, r.x + r.w), y1: Math.max(a.y1, r.y + r.h),
  }),
  { x0: Infinity, y0: Infinity, x1: -Infinity, y1: -Infinity },
);
const cellW = (box.x1 - box.x0) / COLS;
const ROWS = Math.round((box.y1 - box.y0) / cellW / 2); // glyphs ~2x taller than wide
const cellH = (box.y1 - box.y0) / (ROWS * 2);
const coverage = (x0, y0, x1, y1) => {
  let area = 0;
  for (const r of rects) {
    const w = Math.min(x1, r.x + r.w) - Math.max(x0, r.x);
    if (w <= 0) continue;
    const h = Math.min(y1, r.y + r.h) - Math.max(y0, r.y);
    if (h <= 0) continue;
    area += w * h;
  }
  return area / ((x1 - x0) * (y1 - y0));
};
const THRESH = 0.32;
const half = (cx, ry) =>
  coverage(box.x0 + cx * cellW, box.y0 + ry * cellH, box.x0 + (cx + 1) * cellW, box.y0 + (ry + 1) * cellH) > THRESH;
const lines = [];
for (let ry = 0; ry < ROWS; ry++) {
  let line = '';
  for (let cx = 0; cx < COLS; cx++) {
    const top = half(cx, ry * 2);
    const bot = half(cx, ry * 2 + 1);
    line += top && bot ? '█' : top ? '▀' : bot ? '▄' : ' ';
  }
  lines.push(line.replace(/\s+$/, ''));
}
while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
const ascii = lines.join('\n') + '\n';
const asciiPath = path.join(OUT_DIR, 'logo.ascii.txt');
fs.writeFileSync(asciiPath, ascii);
console.log(`wrote ${asciiPath} (${lines.length} rows x ${COLS} cols)`);
